# Symbolic check of the Gram determinants (no orthogonality assumption) and parity of the fake term.
import sympy as sp
dt = sp.symbols('dt', positive=True)
n = 3  # generic vectors in R^3 per frame block (enough for generic position)
A = sp.Matrix(sp.symbols('A0:%d' % n)); B = sp.Matrix(sp.symbols('B0:%d' % n)); C = sp.Matrix(sp.symbols('C0:%d' % n))
Z = sp.zeros(n, 1)
# two-frame R(th, om) = (f(th), f(th - om dt)): d/dth = (A, B), d/dom = (0, -dt B), A = f'(th), B = f'(th - om dt)
u = A.col_join(B); v = Z.col_join(-dt * B)
G = sp.Matrix([[u.dot(u), u.dot(v)], [v.dot(u), v.dot(v)]])
print("2-frame det G - dt^2 |A|^2 |B|^2 =", sp.simplify(G.det() - dt**2 * A.dot(A) * B.dot(B)))
# two-frame with true previous state g(th, om): d/dth = (A, g_th B), d/dom = (0, g_om B)
gth, gom = sp.symbols('g_th g_om')
u = A.col_join(gth * B); v = Z.col_join(gom * B)
G = sp.Matrix([[u.dot(u), u.dot(v)], [v.dot(u), v.dot(v)]])
print("2-frame (exact flow) det G - g_om^2 |A|^2 |B|^2 =", sp.simplify(G.det() - gom**2 * A.dot(A) * B.dot(B)))
# symmetric 3-frame (f(th+om dt), f(th), f(th-om dt)): d/dth = (C, A, B), d/dom = (dt C, 0, -dt B)
u = C.col_join(A).col_join(B); v = (dt * C).col_join(Z).col_join(-dt * B)
G = sp.Matrix([[u.dot(u), u.dot(v)], [v.dot(u), v.dot(v)]])
target = dt**2 * (4 * C.dot(C) * B.dot(B) + A.dot(A) * (C.dot(C) + B.dot(B)))
print("3-frame det G - dt^2[4|C|^2|B|^2 + |A|^2(|C|^2+|B|^2)] =", sp.simplify(sp.expand(G.det() - target)))
